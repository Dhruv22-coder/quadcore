export function getLocalizedCropDisplayName(cropName: string, lang: Language): string {
  const lower = cropName.toLowerCase();
  for (const [key, names] of Object.entries(CROP_LOCAL_NAMES)) {
    if (lower.includes(key)) {
      return names[lang] || names['en'] || cropName;
    }
  }
  return cropName;
}
